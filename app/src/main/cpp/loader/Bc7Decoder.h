struct ModeInfo {
    uint8_t subsets, partBits, rotBits, selBits, colorBits, alphaBits, endpointPBits, sharedPBits, indexBits, index2Bits;
};
inline constexpr ModeInfo kModes[8] = {
    {3, 4, 0, 0, 4, 0, 1, 0, 3, 0}, {2, 6, 0, 0, 6, 0, 0, 1, 3, 0}, {3, 6, 0, 0, 5, 0, 0, 0, 2, 0},
    {2, 6, 0, 0, 7, 0, 1, 0, 2, 0}, {1, 0, 2, 1, 5, 6, 0, 0, 2, 3}, {1, 0, 2, 0, 7, 8, 0, 0, 2, 2},
    {1, 0, 0, 0, 7, 7, 1, 0, 4, 0}, {2, 6, 0, 0, 5, 5, 1, 0, 2, 0},
};

class BitReader {
public:
    explicit BitReader(const uint8_t* b) { std::memcpy(&lo_, b, 8), std::memcpy(&hi_, b + 8, 8); }
    uint32_t read(uint32_t n) {
        uint32_t v = 0;
        for (uint32_t i = 0; i < n; ++i, ++pos_) {
            const uint64_t word = pos_ < 64 ? lo_ : hi_;
            v |= static_cast<uint32_t>((word >> (pos_ & 63u)) & 1u) << i;
        }
        return v;
    }

private:
    uint64_t lo_ = 0, hi_ = 0;
    uint32_t pos_ = 0;
};

inline uint8_t interp(uint8_t e0, uint8_t e1, uint32_t idx, uint32_t bits) {
    static constexpr uint8_t w2[4] = {0, 21, 43, 64};
    static constexpr uint8_t w3[8] = {0, 9, 18, 27, 37, 46, 55, 64};
    static constexpr uint8_t w4[16] = {0, 4, 9, 13, 17, 21, 26, 30, 34, 38, 43, 47, 51, 55, 60, 64};
    const uint32_t w = bits == 2 ? w2[idx] : bits == 3 ? w3[idx] : w4[idx];
    return static_cast<uint8_t>(((64u - w) * e0 + w * e1 + 32u) >> 6);
}

// Un bloque de 16 B -> 16 píxeles RGBA8 (64 B). Modo inválido (byte 0 = 0): negro transparente.
inline void decodeBlock(const uint8_t* block, uint8_t* out) {
    uint32_t mode = 0;
    while (mode < 8 && ((block[0] >> mode) & 1u) == 0) ++mode;
    if (mode >= 8) {
        std::memset(out, 0, 64);
        return;
    }
    const ModeInfo& mi = kModes[mode];
    BitReader br(block);
    br.read(mode + 1);
    const uint32_t partition = br.read(mi.partBits);
    const uint32_t rotation = br.read(mi.rotBits);
    const uint32_t indexSel = br.read(mi.selBits);
    const uint32_t numEp = mi.subsets * 2u;

    uint32_t ep[6][4] = {};  // extremos sin cuantizar [extremo][canal]
    for (uint32_t c = 0; c < 3; ++c) {
        for (uint32_t e = 0; e < numEp; ++e) ep[e][c] = br.read(mi.colorBits);
    }
    if (mi.alphaBits != 0) {
        for (uint32_t e = 0; e < numEp; ++e) ep[e][3] = br.read(mi.alphaBits);
    }
    uint32_t pbit[6] = {};
    const bool hasP = mi.endpointPBits != 0 || mi.sharedPBits != 0;
    if (mi.endpointPBits != 0) {
        for (uint32_t e = 0; e < numEp; ++e) pbit[e] = br.read(1);
    } else if (mi.sharedPBits != 0) {
        for (uint32_t s = 0; s < mi.subsets; ++s) pbit[s * 2] = pbit[s * 2 + 1] = br.read(1);
    }
    uint8_t epq[6][4];
    for (uint32_t e = 0; e < numEp; ++e) {
        for (uint32_t c = 0; c < 4; ++c) {
            uint32_t bits = c < 3 ? mi.colorBits : mi.alphaBits;
            if (bits == 0) {  // sin alfa: opaco
                epq[e][c] = 255;
                continue;
            }
            uint32_t v = ep[e][c];
            if (hasP) {
                v = (v << 1) | pbit[e];
                ++bits;
            }
            v <<= (8 - bits);
            v |= v >> bits;
            epq[e][c] = static_cast<uint8_t>(v);
        }
    }

    auto subsetOf = [&](uint32_t i) -> uint32_t {
        if (mi.subsets == 2) return kPartition2[partition][i];
        if (mi.subsets == 3) return kPartition3[partition][i];
        return 0;
    };
    auto isAnchor = [&](uint32_t i) -> bool {
        if (i == 0) return true;
        if (mi.subsets == 2) return i == kAnchor2[partition];
        if (mi.subsets == 3) return i == kAnchor3a[partition] || i == kAnchor3b[partition];
        return false;
    };
    uint32_t idx1[16], idx2[16] = {};
    for (uint32_t i = 0; i < 16; ++i) idx1[i] = br.read(isAnchor(i) ? mi.indexBits - 1u : mi.indexBits);
    if (mi.index2Bits != 0) {
        for (uint32_t i = 0; i < 16; ++i) idx2[i] = br.read(i == 0 ? mi.index2Bits - 1u : mi.index2Bits);
    }

    for (uint32_t i = 0; i < 16; ++i) {
        const uint32_t s = subsetOf(i);
        const uint8_t* e0 = epq[s * 2];
        const uint8_t* e1 = epq[s * 2 + 1];
        uint8_t px[4];
        if (mi.index2Bits != 0) {
            // Modos 4/5: color y alfa con conjuntos de índices distintos (selector en el modo 4).
            const bool swap = indexSel != 0;
            const uint32_t ci = swap ? idx2[i] : idx1[i], cb = swap ? mi.index2Bits : mi.indexBits;
            const uint32_t ai = swap ? idx1[i] : idx2[i], ab = swap ? mi.indexBits : mi.index2Bits;
            for (int c = 0; c < 3; ++c) px[c] = interp(e0[c], e1[c], ci, cb);
            px[3] = interp(e0[3], e1[3], ai, ab);
        } else {
            for (int c = 0; c < 4; ++c) px[c] = interp(e0[c], e1[c], idx1[i], mi.indexBits);
        }
        if (rotation == 1) std::swap(px[0], px[3]);
        else if (rotation == 2) std::swap(px[1], px[3]);
        else if (rotation == 3) std::swap(px[2], px[3]);
        std::memcpy(out + i * 4, px, 4);
    }
}

